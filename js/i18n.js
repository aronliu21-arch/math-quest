let lang = 'en';
export function setLang(l) { lang = l === 'zh' ? 'zh' : 'en'; document.documentElement.lang = lang === 'zh' ? 'zh-Hant-TW' : 'en'; }
export function getLang() { return lang; }

export function t(k, vars) {
  const e = STR[k];
  if (!e) return k;
  let s = e[lang === 'zh' ? 1 : 0];
  if (Array.isArray(s)) s = s[Math.floor(Math.random() * s.length)];
  if (vars) for (const [k2, v] of Object.entries(vars)) s = s.split(`{${k2}}`).join(v);
  return s;
}

// {en, zh} objects
export function L(o) { if (!o) return ''; if (typeof o === 'string') return o; return o[lang] || o.en; }
